export const DEFAULT_LANGUAGE: Language = "en";
export const LANGUAGE_COOKIE_NAME = "hisaabkitaab-language";
export const LANGUAGE_STORAGE_KEY = "hisaabkitaab-language-pref";

export type TranslationKey = keyof typeof translations.en;

export function normalizeLanguage(value: unknown): Language {
  const lang = typeof value === "string" ? value : String(value);
  return lang === "hi" ? "hi" : DEFAULT_LANGUAGE;
}

export function getTranslation(language: Language, key: TranslationKey): string {
  const normalizedLanguage = normalizeLanguage(language);
  const dict = translations[normalizedLanguage] as Partial<Record<TranslationKey, string>>;
  const defaultDict = translations[DEFAULT_LANGUAGE] as Record<TranslationKey, string>;

  return dict[key] || defaultDict[key] || key;
}

export function createTranslator(language: Language) {
  return (key: TranslationKey) => getTranslation(language, key);
}
